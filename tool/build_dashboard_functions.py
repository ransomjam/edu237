"""Bundle each Edge Function into ONE self-contained .ts file.

The deployable source of truth stays supabase/functions/<name>/index.ts, which
imports the shared Fapshi client and Supabase helpers from ../_shared. The
Supabase dashboard editor is easiest to use with a single file per function, so
this script inlines those shared modules and hoists the one remote import to the
top.

    python tool/build_dashboard_functions.py

Output: tool/dashboard/<function-name>.ts

Nothing here changes behaviour - it is the same code with the imports resolved
by hand. Re-run it after editing anything under supabase/functions/.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FUNCTIONS = ROOT / "supabase" / "functions"
OUT = ROOT / "tool" / "dashboard"

REMOTE_IMPORT = (
    'import {\n'
    '  createClient,\n'
    '  type SupabaseClient,\n'
    '} from "https://esm.sh/@supabase/supabase-js@2.47.10";\n'
)

IMPORT_RE = re.compile(r'^import\s*(?:\{[^}]*\}|\w+)\s*from\s*"[^"]+";\s*$',
                       re.MULTILINE | re.DOTALL)


def strip_imports(source: str) -> str:
    """Drop every import statement; they are hoisted or inlined instead."""
    return IMPORT_RE.sub("", source).strip() + "\n"


def strip_exports(source: str) -> str:
    """`export` is meaningless once everything lives in one file."""
    source = re.sub(r'^export\s+(?=(async\s+)?function|const|class|interface|type)',
                    '', source, flags=re.MULTILINE)
    return source


def build(name: str) -> Path:
    index = (FUNCTIONS / name / "index.ts").read_text(encoding="utf-8")
    fapshi = (FUNCTIONS / "_shared" / "fapshi.ts").read_text(encoding="utf-8")
    helpers = (FUNCTIONS / "_shared" / "supabase.ts").read_text(encoding="utf-8")

    header = (
        "// " + "=" * 75 + "\n"
        f"// Camiva - {name} (single-file build for the Supabase dashboard)\n"
        "// " + "=" * 75 + "\n"
        "//\n"
        "// GENERATED by tool/build_dashboard_functions.py - do not edit here.\n"
        f"// Edit supabase/functions/{name}/index.ts and re-run that script.\n"
        "//\n"
        "// Paste this whole file into the dashboard's Edge Function editor as\n"
        f"// the function named exactly: {name}\n"
        "// " + "=" * 75 + "\n\n"
    )

    parts = [
        header,
        REMOTE_IMPORT,
        "\n// ---- inlined from supabase/functions/_shared/fapshi.ts ----------------\n\n",
        strip_exports(strip_imports(fapshi)),
        "\n// ---- inlined from supabase/functions/_shared/supabase.ts --------------\n\n",
        strip_exports(strip_imports(helpers)),
        f"\n// ---- from supabase/functions/{name}/index.ts " + "-" * 20 + "\n\n",
        strip_imports(index),
    ]
    body = "".join(parts)

    OUT.mkdir(parents=True, exist_ok=True)
    target = OUT / f"{name}.ts"
    target.write_text(body, encoding="utf-8")
    return target


def main() -> None:
    names = [
        "payments-create",
        "payments-verify",
        "withdrawals-request",
        "fapshi-webhook",
        "send-reminder",
        "push-fanout",
        "pin-reset-request",
        "pin-reset-confirm",
    ]
    for name in names:
        target = build(name)
        text = target.read_text(encoding="utf-8")
        # Fail loudly rather than hand over a file that cannot run.
        assert "../_shared" not in text, f"{name}: a shared import survived"
        assert "Deno.serve" in text, f"{name}: no request handler"
        print(f"{target.relative_to(ROOT)}  ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
