/// Cameroon GCE-oriented topic catalogue.
///
/// Provides common topic suggestions organised by Form → Subject.
/// Used to power topic selection in the Create Activity screen so
/// teachers mostly tap rather than type.
///
/// This is intentionally NOT exhaustive — it covers the most common
/// O-Level and A-Level topics to give teachers a useful starting point.
/// The teacher can always enter a custom topic via "Other topic".
abstract final class TopicCatalogue {
  /// Returns suggested topics for the given [form] and [subject].
  /// Falls back to an empty list if no catalogue entry exists.
  static List<String> topicsFor(String form, String subject) {
    final formTopics = _catalogue[form];
    if (formTopics == null) return const [];
    return formTopics[subject] ?? const [];
  }

  /// Returns all subjects that have catalogue entries for a given form.
  static List<String> subjectsFor(String form) {
    final formTopics = _catalogue[form];
    if (formTopics == null) return const [];
    return formTopics.keys.toList();
  }

